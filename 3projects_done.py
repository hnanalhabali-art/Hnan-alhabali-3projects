def segment_name(r):
    r = r.sort_values(ascending=False)
    if (r < 0.8).all():
        return "Low-spend small buyers"
    if (r >= 1.2).sum() >= 4:
        return "High-volume multi-category buyers"
    high = r[r >= 1.2].index.tolist()[:2]
    if not high:
        return "Average-spend buyers (strongest in %s)" % r.index[0].replace("_", " ")
    return " & ".join(h.replace("_", " ") for h in high) + "-focused buyers"

OFFERS = {
    "Fresh": "Weekly fresh-produce bundle with a delivery-frequency discount",
    "Milk": "Volume discount on Milk, Grocery and Detergents/Paper bundles",
    "Grocery": "Volume discount on Grocery, Milk and Detergents/Paper bundles",
    "Detergents_Paper": "Bulk Detergents/Paper pack discount combined with Grocery staples",
    "Frozen": "Frozen-goods volume discount with cold-chain delivery priority",
    "Delicassen": "Premium delicatessen range introduction with sample boxes",
}
def segment_offer(r):
    r = r.sort_values(ascending=False)
    if (r < 0.8).all():
        return "Starter bundle with a free-delivery threshold to grow basket size"
    if (r >= 1.2).sum() >= 4:
        return "Key-account programme: volume rebates and a dedicated account manager"
    return OFFERS[r.index[0]]

def characteristics(r):
    hi = r[r >= 1.2].sort_values(ascending=False)
    lo = r[r <= 0.8].sort_values()
    parts = []
    if len(hi): parts.append("High: " + ", ".join(f"{c} ({v:.1f}x avg)" for c, v in hi.items()))
    if len(lo): parts.append("Low: " + ", ".join(f"{c} ({v:.1f}x avg)" for c, v in lo.items()))
    return "; ".join(parts) if parts else "Close to average in all categories"

