"""## Task 7 – Evaluate baseline and all six experiments on the validation set"""

def evaluate(model, Xs, ys):
    pred = model.predict(Xs)
    return {"Accuracy":        accuracy_score(ys, pred),
            "Macro Precision": precision_score(ys, pred, average="macro", zero_division=0),
            "Macro Recall":    recall_score(ys, pred, average="macro", zero_division=0),
            "Macro F1":        f1_score(ys, pred, average="macro", zero_division=0)}

